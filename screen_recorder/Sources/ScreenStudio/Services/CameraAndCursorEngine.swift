import Foundation
import CoreGraphics

// MARK: - Evaluated Frame State

public struct ActiveClickRipple: Equatable {
    public var position: CGPoint // Normalized (0...1, 0...1) in screen space
    public var progress: CGFloat // 0.0 ... 1.0
    public var alpha: CGFloat
}

public struct EvaluatedCursorState: Equatable {
    /// Smoothed normalized position (0...1, 0...1) in screen coordinates (top-left origin)
    public var position: CGPoint
    /// Velocity in normalized screen units per second
    public var velocity: CGVector
    /// Dynamic scale multiplier from click press/release bounce (e.g. 0.80 ... 1.08)
    public var clickBounceScale: CGFloat
    /// Opacity multiplier (1.0 when active, fades if auto-hide idle cursor is enabled)
    public var opacity: CGFloat
    /// Active expanding click ripples at current timestamp
    public var ripples: [ActiveClickRipple]
}

public struct EvaluatedCameraState: Equatable {
    /// Current zoom factor (1.0 = unzoomed)
    public var zoomScale: CGFloat
    /// Normalized center point (0...1, 0...1) in screen coordinates (top-left origin)
    public var focusCenter: CGPoint
    /// Normalized visible rect in screen coordinates (0...1, 0...1)
    public var visibleNormalizedRect: CGRect
    /// Active zoom segment ID if currently inside or transitioning a segment
    public var activeSegmentID: UUID?
}

// MARK: - Camera & Cursor Evaluator Engine

public enum CameraAndCursorEngine {

    // MARK: - Auto-Zoom Generation from Clicks

    /// Automatically generates smooth Screen Studio-style zoom segments from recorded click events.
    public static func generateAutoZoomSegments(
        from telemetry: CursorTelemetryTrack,
        duration: TimeInterval,
        defaultScale: CGFloat = 2.0,
        preRoll: TimeInterval = 0.28,
        holdAfterClick: TimeInterval = 1.55,
        mergeThreshold: TimeInterval = 2.10
    ) -> [ZoomSegment] {
        let sortedClicks = telemetry.clicks.sorted { $0.time < $1.time }
        guard !sortedClicks.isEmpty else { return [] }

        var segments: [ZoomSegment] = []

        for click in sortedClicks {
            let proposedStart = max(0.0, click.time - preRoll)
            let proposedEnd = min(duration, max(click.releaseTime, click.time) + holdAfterClick)
            guard proposedEnd > proposedStart + 0.3 else { continue }

            if var last = segments.last, proposedStart <= last.endTime + mergeThreshold {
                // Merge consecutive clicks into a continuous zoom segment
                last.endTime = max(last.endTime, proposedEnd)
                segments[segments.count - 1] = last
            } else {
                let segment = ZoomSegment(
                    startTime: proposedStart,
                    endTime: proposedEnd,
                    zoomScale: defaultScale,
                    targetMode: .followCursor,
                    targetPoint: click.point,
                    isAutoGenerated: true
                )
                segments.append(segment)
            }
        }

        return segments
    }

    // MARK: - Cursor Evaluation (Spring Smoothing, Velocity, Click Bounce & Ripples)

    public static func evaluateCursor(
        at time: TimeInterval,
        telemetry: CursorTelemetryTrack,
        style: CursorStyle
    ) -> EvaluatedCursorState {
        let samples = telemetry.samples
        guard !samples.isEmpty else {
            return EvaluatedCursorState(
                position: CGPoint(x: 0.5, y: 0.5),
                velocity: .zero,
                clickBounceScale: 1.0,
                opacity: 1.0,
                ripples: []
            )
        }

        // Compute smoothed cursor position & instantaneous velocity using windowed EMA / spring kernel
        let smoothing = min(max(style.smoothingFactor, 0.0), 0.98)
        let pos: CGPoint
        let vel: CGVector

        if smoothing < 0.02 {
            pos = rawInterpolatedCursorPosition(at: time, in: samples)
            let dt = 1.0 / 60.0
            let prev = rawInterpolatedCursorPosition(at: max(0, time - dt), in: samples)
            vel = CGVector(dx: (pos.x - prev.x) / dt, dy: (pos.y - prev.y) / dt)
        } else {
            // Evaluate critically damped filter over surrounding time window [-window, +window*0.35]
            // A small lookahead makes cursor motion anticipate movement like Screen Studio's spring curve
            let halfWindow = 0.03 + smoothing * 0.20
            let dtStep = 1.0 / 120.0
            let startT = max(0, time - halfWindow)
            let steps = max(2, Int((time - startT) / dtStep))

            var filtered = rawInterpolatedCursorPosition(at: startT, in: samples)
            var velocityX: CGFloat = 0
            var velocityY: CGFloat = 0

            // Critically damped spring constants omega (natural frequency)
            let omega: CGFloat = CGFloat(42.0 - smoothing * 30.0) // ranges from 42 rad/s (snappy) to 12 rad/s (silky)

            for i in 1...steps {
                let sampleT = startT + Double(i) * dtStep
                let target = rawInterpolatedCursorPosition(at: sampleT, in: samples)
                let dt = CGFloat(dtStep)

                // Critically damped spring step: x'' = omega^2 * (target - x) - 2 * omega * x'
                let accelX = (omega * omega) * (target.x - filtered.x) - (2.0 * omega) * velocityX
                let accelY = (omega * omega) * (target.y - filtered.y) - (2.0 * omega) * velocityY

                velocityX += accelX * dt
                velocityY += accelY * dt
                filtered.x += velocityX * dt
                filtered.y += velocityY * dt
            }

            pos = CGPoint(
                x: min(max(filtered.x, 0.0), 1.0),
                y: min(max(filtered.y, 0.0), 1.0)
            )
            vel = CGVector(dx: velocityX, dy: velocityY)
        }

        // Evaluate click bounce & ripples
        var bounceScale: CGFloat = 1.0
        var ripples: [ActiveClickRipple] = []
        let rippleDuration: TimeInterval = 0.52

        for click in telemetry.clicks {
            let elapsed = time - click.time
            if elapsed >= 0 && elapsed <= rippleDuration {
                let p = CGFloat(elapsed / rippleDuration)
                // Cubic ease-out expansion
                let easedProgress = 1.0 - pow(1.0 - p, 3.0)
                let alpha = pow(1.0 - p, 1.8)
                if style.showClickRipple {
                    ripples.append(
                        ActiveClickRipple(
                            position: click.point,
                            progress: easedProgress,
                            alpha: alpha
                        )
                    )
                }
            }

            if style.clickBounceAnimation {
                if time >= click.time && time <= click.releaseTime {
                    // Mouse pressed down -> shrink smoothly to 0.78
                    let pressElapsed = min(1.0, (time - click.time) / 0.06)
                    let shrink = 1.0 - 0.22 * smoothStep(CGFloat(pressElapsed))
                    bounceScale = min(bounceScale, shrink)
                } else if time > click.releaseTime && time <= click.releaseTime + 0.24 {
                    // Mouse released -> spring back with slight overshoot
                    let rel = CGFloat((time - click.releaseTime) / 0.24)
                    let springOvershoot = 1.0 + 0.12 * sin(rel * .pi) * (1.0 - rel)
                    bounceScale = springOvershoot
                }
            }
        }

        // Auto-hide idle cursor check
        var opacity: CGFloat = 1.0
        if style.autoHideIdleCursor {
            let speed = hypot(vel.dx, vel.dy)
            if speed < 0.005 && ripples.isEmpty {
                opacity = 0.35
            }
        }

        return EvaluatedCursorState(
            position: pos,
            velocity: vel,
            clickBounceScale: bounceScale,
            opacity: opacity,
            ripples: ripples
        )
    }

    // MARK: - Camera Evaluation (Smooth Zoom Transitions & Cursor Follow)

    public static func evaluateCamera(
        at time: TimeInterval,
        zoomSegments: [ZoomSegment],
        springSpeed: ZoomSpringSpeed,
        telemetry: CursorTelemetryTrack
    ) -> EvaluatedCameraState {
        let sorted = zoomSegments.sorted { $0.startTime < $1.startTime }
        guard !sorted.isEmpty else {
            return EvaluatedCameraState(
                zoomScale: 1.0,
                focusCenter: CGPoint(x: 0.5, y: 0.5),
                visibleNormalizedRect: CGRect(x: 0, y: 0, width: 1, height: 1),
                activeSegmentID: nil
            )
        }

        let transitionDur = springSpeed.transitionDuration
        var totalWeight: CGFloat = 0.0
        var weightedScaleDelta: CGFloat = 0.0
        var weightedFocusX: CGFloat = 0.0
        var weightedFocusY: CGFloat = 0.0
        var primarySegmentID: UUID?

        for segment in sorted {
            // Segment influence envelope:
            // Ramps up from [startTime - transitionDur * 0.4, startTime + transitionDur * 0.6]
            // Holds at 1.0 until endTime - transitionDur * 0.3
            // Ramps down from [endTime - transitionDur * 0.3, endTime + transitionDur * 0.7]
            let inStart = segment.startTime - transitionDur * 0.35
            let inEnd = segment.startTime + transitionDur * 0.65
            let outStart = max(inEnd, segment.endTime - transitionDur * 0.30)
            let outEnd = segment.endTime + transitionDur * 0.70

            guard time >= inStart && time <= outEnd else { continue }

            let envelope: CGFloat
            if time < inEnd {
                let u = CGFloat((time - inStart) / max(0.05, inEnd - inStart))
                envelope = springEaseInOut(u)
            } else if time <= outStart {
                envelope = 1.0
            } else {
                let u = CGFloat((time - outStart) / max(0.05, outEnd - outStart))
                envelope = 1.0 - springEaseInOut(u)
            }

            guard envelope > 0.0001 else { continue }

            let targetFocus = segmentFocusPoint(
                for: segment,
                at: time,
                springSpeed: springSpeed,
                telemetry: telemetry
            )

            totalWeight += envelope
            weightedScaleDelta += envelope * (segment.zoomScale - 1.0)
            weightedFocusX += envelope * targetFocus.x
            weightedFocusY += envelope * targetFocus.y
            primarySegmentID = segment.id
        }

        guard totalWeight > 0.0001 else {
            return EvaluatedCameraState(
                zoomScale: 1.0,
                focusCenter: CGPoint(x: 0.5, y: 0.5),
                visibleNormalizedRect: CGRect(x: 0, y: 0, width: 1, height: 1),
                activeSegmentID: nil
            )
        }

        let clampedWeight = min(totalWeight, 1.0)
        let currentScale = 1.0 + (weightedScaleDelta / max(1.0, totalWeight))
        let targetX = weightedFocusX / totalWeight
        let targetY = weightedFocusY / totalWeight

        // Blend between screen center (0.5, 0.5) when unzoomed and target focus when zoomed
        let focusX = 0.5 + (targetX - 0.5) * clampedWeight
        let focusY = 0.5 + (targetY - 0.5) * clampedWeight

        // Clamp visible rect so camera never pans past the edges of the screen
        let visibleW = 1.0 / max(1.0, currentScale)
        let visibleH = 1.0 / max(1.0, currentScale)

        let halfW = visibleW * 0.5
        let halfH = visibleH * 0.5

        let clampedCenterX = min(max(focusX, halfW), 1.0 - halfW)
        let clampedCenterY = min(max(focusY, halfH), 1.0 - halfH)

        let rect = CGRect(
            x: clampedCenterX - halfW,
            y: clampedCenterY - halfH,
            width: visibleW,
            height: visibleH
        )

        return EvaluatedCameraState(
            zoomScale: currentScale,
            focusCenter: CGPoint(x: clampedCenterX, y: clampedCenterY),
            visibleNormalizedRect: rect,
            activeSegmentID: primarySegmentID
        )
    }

    // MARK: - Internal Interpolation Helpers

    private static func segmentFocusPoint(
        for segment: ZoomSegment,
        at time: TimeInterval,
        springSpeed: ZoomSpringSpeed,
        telemetry: CursorTelemetryTrack
    ) -> CGPoint {
        switch segment.targetMode {
        case .fixedPoint:
            return segment.targetPoint
        case .followCursor:
            guard !telemetry.samples.isEmpty else {
                return segment.targetPoint
            }
            // Heavy camera damping so small cursor movements don't shake the entire screen
            var cameraCursorStyle = CursorStyle()
            cameraCursorStyle.smoothingFactor = min(0.95, 0.78 + springSpeed.cursorFollowSmoothing)
            let cursorEval = evaluateCursor(
                at: min(max(time, segment.startTime), segment.endTime),
                telemetry: telemetry,
                style: cameraCursorStyle
            )
            return cursorEval.position
        }
    }

    public static func rawInterpolatedCursorPosition(
        at time: TimeInterval,
        in samples: [CursorSample]
    ) -> CGPoint {
        guard let first = samples.first else { return CGPoint(x: 0.5, y: 0.5) }
        if time <= first.time { return first.point }
        guard let last = samples.last else { return first.point }
        if time >= last.time { return last.point }

        // Binary search for surrounding samples
        var low = 0
        var high = samples.count - 1
        while low + 1 < high {
            let mid = (low + high) / 2
            if samples[mid].time <= time {
                low = mid
            } else {
                high = mid
            }
        }

        let s0 = samples[low]
        let s1 = samples[high]
        let span = s1.time - s0.time
        guard span > 0.00001 else { return s0.point }
        let t = CGFloat((time - s0.time) / span)
        return CGPoint(
            x: s0.x + (s1.x - s0.x) * t,
            y: s0.y + (s1.y - s0.y) * t
        )
    }

    private static func smoothStep(_ x: CGFloat) -> CGFloat {
        let t = min(max(x, 0.0), 1.0)
        return t * t * (3.0 - 2.0 * t)
    }

    /// Quintic smooth S-curve with gentle spring-like acceleration and deceleration
    public static func springEaseInOut(_ x: CGFloat) -> CGFloat {
        let t = min(max(x, 0.0), 1.0)
        return t * t * t * (t * (t * 6.0 - 15.0) + 10.0)
    }
}
